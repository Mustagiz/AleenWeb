import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args:['--disable-background-timer-throttling','--disable-renderer-backgrounding','--disable-backgrounding-occluded-windows'] });
const ctx = await browser.newContext({ viewport:{width:1440,height:900} });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await cdp.send('Network.setCacheDisabled',{cacheDisabled:true});
await page.addInitScript(() => { window.__lt=[]; new PerformanceObserver(l => l.getEntries().forEach(e=>window.__lt.push({start:Math.round(e.startTime),dur:Math.round(e.duration)}))).observe({type:'longtask', buffered:true}); });
const errors=[]; const bad=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('console', m=>{if(m.type()==='error')errors.push(m.text());});
page.on('response', r=>{if(r.status()>=400)bad.push(`${r.status()} ${r.url()}`);});
const t=Date.now();
await page.goto('http://127.0.0.1:4173/', { waitUntil:'domcontentloaded' });
await page.waitForTimeout(120);
const early = await page.evaluate(() => ({ body:document.body.className, textOpacity:getComputedStyle(document.querySelector('.hero h1')).opacity, btnOpacity:getComputedStyle(document.querySelector('.hero-actions')).opacity, fallbackOpacity:getComputedStyle(document.querySelector('.fallback')).opacity, sceneOpacity:getComputedStyle(document.querySelector('#scene')).opacity, badge:document.querySelector('#render-label')?.textContent }));
await page.screenshot({path:'shots/fast-early.png'});
await page.waitForFunction(() => document.body.classList.contains('is-scene-ready'), null, {timeout:30000});
const ms=Date.now()-t;
await page.waitForTimeout(1500);
await page.screenshot({path:'shots/fast-final.png'});
const data=await page.evaluate(() => ({now:Math.round(performance.now()), longtasks:window.__lt, body:document.body.className, label:document.querySelector('#render-label')?.textContent, sceneOpacity:getComputedStyle(document.querySelector('#scene')).opacity}));
console.log('scene-ready',ms,'early',JSON.stringify(early),'data',JSON.stringify(data,null,2),'errors',errors,'bad',bad);
await browser.close();
