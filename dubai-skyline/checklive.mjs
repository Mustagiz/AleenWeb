import { chromium } from 'playwright-core';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--disable-background-timer-throttling','--disable-renderer-backgrounding']});
const page=await browser.newPage({viewport:{width:1280,height:800}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const t=Date.now();
await page.goto('http://127.0.0.1:4174/',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(250);
const early=await page.evaluate(()=>({cls:document.body.className,opacity:getComputedStyle(document.querySelector('.hero h1')).opacity,label:document.querySelector('#render-label')?.textContent}));
await page.waitForFunction(()=>document.body.classList.contains('is-scene-ready'),null,{timeout:20000});
console.log('ready',Date.now()-t,'ms',early,'errors',errors);
await page.waitForTimeout(1200);
await page.screenshot({path:'shots/live4174.png'});
await browser.close();
