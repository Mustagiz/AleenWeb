import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args:['--disable-background-timer-throttling','--disable-renderer-backgrounding','--disable-backgrounding-occluded-windows'] });
const ctx = await browser.newContext({ viewport:{width:1440,height:900} });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await cdp.send('Network.setCacheDisabled',{cacheDisabled:true});
await page.addInitScript(() => { window.__lt=[]; new PerformanceObserver(l => l.getEntries().forEach(e=>window.__lt.push({start:Math.round(e.startTime),dur:Math.round(e.duration)}))).observe({type:'longtask', buffered:true}); });
const t=Date.now();
await page.goto('http://127.0.0.1:4173/', { waitUntil:'domcontentloaded' });
await page.waitForTimeout(120);
const early = await page.evaluate(() => ({body:document.body.className, loader:!!document.querySelector('#loader'), sceneOpacity:getComputedStyle(document.querySelector('#scene')).opacity, fallbackOpacity:getComputedStyle(document.querySelector('.fallback')).opacity, text:document.querySelector('.hero h1').textContent.trim().replace(/\s+/g,' ')}));
await page.screenshot({path:'shots/cold-120ms.png'});
await page.waitForFunction(() => document.body.classList.contains('is-scene-ready'), null, {timeout:30000});
const ms=Date.now()-t;
await page.waitForTimeout(1400);
await page.screenshot({path:'shots/optimized-2.png'});
const data=await page.evaluate(() => ({now:Math.round(performance.now()), phase:window.__phase, longtasks:window.__lt, body:document.body.className, label:document.querySelector('#render-label')?.textContent, sceneOpacity:getComputedStyle(document.querySelector('#scene')).opacity}));
console.log('scene-ready',ms,'early',JSON.stringify(early),'data',JSON.stringify(data,null,2));
await browser.close();
